#!/bin/bash
set -euo pipefail
SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)"
INSTALL_ROOT="${GITGO_LINUX_INSTALL_ROOT:-${XDG_DATA_HOME:-$HOME/.local/share}/gitgo/app}"
BIN_DIR="${GITGO_LINUX_BIN_DIR:-$HOME/.local/bin}"
UPDATE_PATH=1
START_MARKER="# >>> Gitgo managed PATH >>>"
END_MARKER="# <<< Gitgo managed PATH <<<"
BASH_PROFILE=.profile
while [ "$#" -gt 0 ]; do
  case "$1" in
    --install-root) INSTALL_ROOT="$2"; shift 2 ;;
    --bin-dir) BIN_DIR="$2"; shift 2 ;;
    --no-path-update) UPDATE_PATH=0; shift ;;
    -h|--help) echo 'Usage: install.sh [--install-root DIR] [--bin-dir DIR] [--no-path-update]'; exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
done
[ -f "$SCRIPT_DIR/product.json" ] && [ -f "$SCRIPT_DIR/product.env" ] || { echo 'Release contract missing' >&2; exit 1; }
# Generated by the build; never source an unknown existing target's contract.
source "$SCRIPT_DIR/product.env"
PLATFORM="${GITGO_PRODUCT_PLATFORM:?}"
PRODUCT_ID="${GITGO_PRODUCT_ID:?}"
COMMAND="${GITGO_PRODUCT_COMMAND:?}"
ALIASES=()
read -r -a ALIASES <<< "${GITGO_PRODUCT_ALIASES:-}"
[ "$PLATFORM" = linux ] || { echo 'Not a Linux release' >&2; exit 1; }
case "$(uname -m)" in x86_64|amd64) HOST_ARCH=x86_64 ;; arm64|aarch64) HOST_ARCH=aarch64 ;; *) exit 1 ;; esac
[ "${GITGO_PRODUCT_ARCHITECTURE:?}" = "$HOST_ARCH" ] || { echo 'Package architecture mismatch' >&2; exit 1; }
[ -x "$SCRIPT_DIR/internal/gitgo-host/gitgo-host" ] || { echo 'Native Host missing' >&2; exit 1; }
source "$SCRIPT_DIR/installer-common.sh"
install_transaction
