def test_runtime_hash_covers_dependency_contents_but_ignores_bytecode(environment_root):
    before = environment.snapshot()
    assert before["packages"] == [{"name": "example", "version": "1.0"}]
    cache = environment_root / "__pycache__"
    cache.mkdir(); (cache / "dependency.pyc").write_bytes(b"generated")
    assert environment.snapshot() == before
    (environment_root / "dependency.py").write_bytes(b"version = 2\n")
    assert environment.snapshot()["digest"] != before["digest"]


def test_large_binary_is_hashed_without_exporting_bytes(tmp_path_factory):
    path = tmp_path_factory / "runtime.bin"
    data = b"binary\0" * (3 * 1024 * 1024)
    path.write_bytes(data)
    with ReadRoot(tmp_path_factory) as root, root.open("runtime.bin") as opened:
        assert opened.sha256() == (hashlib.sha256(data).hexdigest(), len(data))
    with ReadRoot(tmp_path_factory) as root, root.open("runtime.bin") as opened:
        with pytest.raises(ReadBoundaryError):
            opened.sha256(max_bytes=32)


def test_fixed_dependency_files_ignore_dirty_workspace(formal_setup):
    _, _, repo = formal_setup
    (repo / "requirements.txt").write_text("example==1.0\n", encoding="utf8")
    git(repo, "add", "requirements.txt"); git(repo, "commit", "-m", "lock dependencies")
    (repo / "requirements.txt").write_text("dirty==99.0\n", encoding="utf8")
    item = prepare(formal_setup)
    assert item["plan"]["dependencies"] == [{"path": "requirements.txt", "sha256": hashlib.sha256(b"example==1.0\n").hexdigest()}]


def test_runtime_changed_after_checks_blocks_formal_until_rechecked(formal_setup, environment_root, monkeypatch):
    item = prepare(formal_setup)
    protocol(monkeypatch)
    checked = command(formal_setup, "verify", item)["item"]
    assert checked["formal_eligible"]
    (environment_root / "dependency.py").write_bytes(b"version = 2\n")
    assert command(formal_setup, "execute", checked)["error"] == "PUBLISH_ENVIRONMENT_CHANGED"
    rechecked = command(formal_setup, "verify", checked, "recheck")["item"]
    assert command(formal_setup, "execute", rechecked, "integrate")["item"]["status"] == "integrated"


def test_runtime_changed_during_tests_never_passes(formal_setup, environment_root, monkeypatch):
    item = prepare(formal_setup)
    protocol(monkeypatch, action=lambda _: (environment_root / "dependency.py").write_bytes(b"changed"))
    checked = command(formal_setup, "verify", item)["item"]
    assert not checked["formal_eligible"]
    assert checked["evidence"][-1]["summary"] == "PUBLISH_ENVIRONMENT_CHANGED"


def test_authorship_filter_checks_transformed_tree_without_changing_source(formal_setup, environment_root, monkeypatch):
    from backend.core.config import Config, ConfigManager
    _, project, repo = formal_setup
    original = "# Generated by ChatGPT\nvalue = 42\n"
    (repo / "module.py").write_text(original, encoding="utf8")
    git(repo, "add", "module.py"); git(repo, "commit", "-m", "module with attribution")
    project.authorship.update(mode="human", strip_code_comments=True)
    ConfigManager.save(Config(projects=[project]))
    item = prepare(formal_setup)
    assert [f["path"] for f in item["plan"]["transformed_files"]] == ["module.py"]
    def assert_filtered(stage):
        assert (stage / "module.py").read_text() == "value = 42\n"
    protocol(monkeypatch, action=assert_filtered)
    checked = command(formal_setup, "verify", item)["item"]
    assert command(formal_setup, "execute", checked)["item"]["status"] == "integrated"
    assert (repo / "module.py").read_text() == original
    assert git(repo, "show", "formal:module.py") == "value = 42"
