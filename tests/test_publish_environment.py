    root = tmp_path_factory / "owned-runtime"
    root.mkdir()
    (root / "python.exe").write_bytes(b"protocol executable")
    (root / "dependency.py").write_bytes(b"version = 1\n")
    metadata = root / "example-1.0.dist-info"
    metadata.mkdir()
    (metadata / "METADATA").write_text("Name: example\nVersion: 1.0\n\n", encoding="utf8")
    monkeypatch.setattr("backend.core.sandbox_access.native_runtime_access", lambda: ([root], []))
    monkeypatch.setattr("backend.core.loop.process_tool_runner.tool_runner_command", lambda: [str(root / "python.exe")])
