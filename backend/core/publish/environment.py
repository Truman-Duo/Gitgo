"""Fixed dependency inputs and content witnesses for the actual native runtime."""
import hashlib
import os
from pathlib import Path
import sys

from .state import PublishError, digest

_LOCKS = {"pyproject.toml", "poetry.lock", "uv.lock", "pipfile", "pipfile.lock", "setup.cfg",
          "package.json", "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock", "bun.lockb",
          "cargo.toml", "cargo.lock", "go.mod", "go.sum", "gemfile", "gemfile.lock", "environment.yml"}


def dependencies(files):
    return [{"path": name, "sha256": hashlib.sha256(raw).hexdigest()}
            for name, _, _, raw in files
            if Path(name).name.casefold() in _LOCKS
            or Path(name).name.casefold().startswith("requirements") and name.casefold().endswith(".txt")]


def snapshot():
    """Read Host-selected runtime roots; never import project code or packages.

    Hash all immutable runtime files, including package metadata and native
    libraries. Only generated bytecode is omitted. No credentials/environment
    variables or absolute installation paths are persisted.
    """
    import platform
    from backend.core.sandbox_access import native_runtime_access
    from backend.core.loop.process_tool_runner import tool_runner_command
    from backend.core.sandbox_read import ReadRoot
    roots, _ = native_runtime_access()
    roots = list(dict.fromkeys(Path(p).resolve(strict=True) for p in roots))
    rows, packages, total = [], [], 0
    try:
        executable = Path(tool_runner_command()[0]).resolve(strict=True)
        with ReadRoot(executable.parent) as acquired, acquired.open(executable.name) as opened:
            executable_hash, _ = opened.sha256()
        for index, root in enumerate(roots):
            with ReadRoot(root) as acquired:
                def unreadable(error):
                    raise error
                for directory, dirs, files in os.walk(root, followlinks=False, onerror=unreadable):
                    for child in [*dirs, *files]:
                        path = Path(directory) / child
                        if path.is_symlink() or path.is_junction():
                            raise PublishError("PUBLISH_ENVIRONMENT_UNSUPPORTED")
                    dirs[:] = sorted(d for d in dirs if d != "__pycache__")
                    for name in sorted(files):
                        if name.endswith((".pyc", ".pyo")):
                            continue
                        relative = (Path(directory) / name).relative_to(root).as_posix()
                        with acquired.open(relative) as opened:
                            fingerprint, size = opened.sha256()
                        total += size
                        if total > 768 * 1024 * 1024 or len(rows) >= 30000:
                            raise PublishError("PUBLISH_ENVIRONMENT_LIMIT")
                        rows.append([index, relative, fingerprint])
                        if name == "METADATA" and Path(directory).name.endswith(".dist-info"):
                            # Package labels are metadata, never imported code.
                            with acquired.open(relative) as opened:
                                text = opened.read_bytes().decode("utf8", errors="replace")[:65536]
                            fields = dict(line.split(": ", 1) for line in text.split("\n\n", 1)[0].splitlines() if ": " in line)
                            packages.append({"name": fields.get("Name", "")[:160], "version": fields.get("Version", "")[:80]})
        body = {"version": 1, "platform": sys.platform, "architecture": platform.machine(), "executable_sha256": executable_hash,
                "files_digest": digest(rows), "file_count": len(rows), "bytes": total,
                "packages": sorted(packages, key=lambda p: (p["name"], p["version"]))}
        return {**body, "digest": digest(body)}
    except (OSError, RuntimeError, ValueError) as exc:
        if isinstance(exc, PublishError):
            raise
        raise PublishError("PUBLISH_ENVIRONMENT_UNAVAILABLE") from exc
